// Package vectors holds the FEE (Filecoin Encryption Envelope)
// cross-implementation test vectors: fixed fixture blobs that must decrypt
// identically under this Go implementation (fee/cose, fee/aesstream,
// fee/ecdhkw, fee/aeskw) and under the TypeScript reference implementation,
// @filoz/filecoin-encryption-envelope (github.com/FilOzone/synapse-sdk,
// packages/filecoin-encryption-envelope), pinned in pull-synapse-fee.sh.
//
// Both follow FIP-1253 with the amendments FilOz's implementation guide
// adopts. The shape, verified against the pinned commit, is:
//
//	blob        = envelope || ciphertext          (detached payload)
//	envelope    = 16([protected, unprotected, null])                for no recipients
//	            | 96([protected, unprotected, null, recipients])    with recipients
//	protected   = {1: alg, 16: "application/vnd.filecoin-encryption+cose", 5: baseNonce,
//	               -1: chunkSize, ? -65789: plaintextLength}
//	unprotected = {}
//	alg         = -65793  (chunked AES-256-GCM-STREAM)
//	body AAD    = [ context, protected, "" ]      context per RFC 9052 §5.3:
//	              "Encrypt" for a tag-96 envelope, "Encrypt0" for tag-16
//	chunk nonce = baseNonce[7] || chunkIndex[4 BE] || lastFlag[1]
//
// An A256KW recipient entry is [ protected, {1: -5, ? 4: kid}, wrappedKey ]
// whose protected header is a zero-length byte string, as RFC 9053 §6.2.1
// requires. Both implementations unwrap it, with or without a kid. An
// ECDH-ES+A256KW entry is [ {1: -31}, {? 4: kid, -1: ephemeralKey}, wrappedKey ];
// the reference has no ECDH-ES unwrap, so that one is asserted on the Go side
// only, in vectors_test.go.
//
// Fixtures live under testdata/<name>/ as blob.bin, plaintext.bin and
// meta.json. TestVectors reads and verifies every fixture. The Go-produced
// fixtures are (re)generated by TestGenerate (guarded by FEE_VECTORS_REGEN=1);
// the TS-produced ones by pull-synapse-fee.sh, which also confirms the
// reference reads the Go-produced fixtures. See README.md.
